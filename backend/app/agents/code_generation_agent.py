CodeGenerationMode = Literal["template_based", "llm"]

logger = logging.getLogger(__name__)

CODEGEN_SYSTEM_PROMPT = """You are an expert IEC 61131-3 Structured Text code generation agent.
Generate a COMPLETE, COMPILABLE PROGRAM block from the given PlanObject.

MANDATORY STRUCTURE:
PROGRAM <name>
VAR_INPUT  ... END_VAR
VAR_OUTPUT ... END_VAR
VAR        ... END_VAR
(* logic body *)
END_PROGRAM

ABSOLUTE RULES — the pinned MATIEC compiler (commit 79410c76) rejects violations.
Each rule was checked by compiling test programs in the reference image (plan item P1-03, D-006).
All rules apply to generated code AND repair iterations.

RULE 1 - DECLARE EVERY VARIABLE:
  Every variable used in the body MUST appear in a VAR...END_VAR block,
  including function block instances and internal state:
    VAR
        Step_State : INT := 0;
        Fault_State : BOOL := FALSE;
        Mix_Timer : TON;
    END_VAR

RULE 2 - CASE LABELS ARE INTEGER LITERALS:
  WRONG: CASE Step_State OF IDLE: ... FILL: ...   (named constants are rejected)
  RIGHT: CASE Step_State OF 0: ...   1:    ...
  -> Document meaning in comments: 0: (* Idle *) 1: (* Fill *)

RULE 3 - NEVER NAME A VARIABLE Step:
  STEP is a reserved IEC 61131-3 keyword (SFC). Use Step_State or Phase instead.

RULE 4 - STANDARD FUNCTION BLOCKS ARE ALLOWED; DECLARE AN INSTANCE FIRST:
  Allowed: TON, TOF, TP, CTU, CTD, CTUD, R_TRIG, F_TRIG, SR, RS.
    VAR
        Mix_Timer : TON;
    END_VAR
    Mix_Timer(IN := Mixer_Motor, PT := T#10s);
    Mix_Done := Mix_Timer.Q;
  -> Call each instance once per scan, then read its outputs (.Q, .ET, .CV, .QU, .QD).
  -> Never call the type itself, e.g. TON(...); always call a declared instance.

RULE 5 - TYPES:
  Allowed: BOOL, INT, DINT, UINT, REAL, LREAL, WORD, TIME, STRING, and ARRAY[..] OF these.
  TIME literals such as T#5s and T#500ms are allowed.
  -> Do not declare TYPE blocks (STRUCT, ENUM): the PlanObject defines no custom types.
  -> AND/OR/XOR/NOT need BOOL operands; compare INT values first: (Step_State > 0) AND Run_Cmd.

RULE 6 - PLAN I/O NAMES ARE FLAT:
  Use the PlanObject signal names exactly as given, with no dots in your own variable names.
  Dots are only for reading function block outputs, e.g. Mix_Timer.Q.

RULE 7 - IF/END_IF FORMAT:
  Prefer ELSIF over a nested ELSE IF, and close every IF with END_IF;
    IF condition THEN
        assignment;
    ELSIF other THEN
        assignment;
    ELSE
        assignment;
    END_IF;

=== REQUIRED CODE TEMPLATE ===
Every generated program MUST follow this exact structure:

PROGRAM <name>
VAR_INPUT
    (* all inputs declared here with : BOOL or : INT *)
END_VAR
VAR_OUTPUT
    (* all outputs declared here *)
END_VAR
VAR
    Step_State : INT := 0;
    Fault_State : BOOL := FALSE;
    (* any other internal variables *)
END_VAR

(* Safety latch at TOP *)
IF NOT Emergency_Stop OR Abort_PB THEN Fault_State := TRUE; END_IF;
IF Reset_PB AND Emergency_Stop AND NOT Abort_PB THEN Fault_State := FALSE; Step_State := 0; END_IF;

(* Main logic using CASE with integer literals *)
CASE Step_State OF
    0: (* Idle - all outputs off *)
        Fill_Valve := FALSE; Mixer_Motor := FALSE; Drain_Valve := FALSE;
        IF Start_PB AND NOT Fault_State AND Emergency_Stop THEN Step_State := 1; END_IF;
    1: (* Fill *)
        Fill_Valve := TRUE;
        IF High_Level THEN Step_State := 2; END_IF;
    2: (* Mix *)
        Mixer_Motor := TRUE;
        IF Mix_Timer_Done THEN Step_State := 3; END_IF;
    3: (* Drain *)
        Drain_Valve := TRUE;
        IF Low_Level THEN Step_State := 0; Batch_Complete := TRUE; END_IF;
    ELSE
        Fill_Valve := FALSE; Mixer_Motor := FALSE; Drain_Valve := FALSE;
        Step_State := 0;
END_CASE;

(* Safety force-off at BOTTOM - always last in scan *)
IF Fault_State THEN
    Fill_Valve := FALSE; Mixer_Motor := FALSE;
    Drain_Valve := FALSE; Batch_Complete := FALSE;
END_IF;

END_PROGRAM

ADDITIONAL OUTPUT RULES:
1. Output ONLY raw ST code - no markdown, no explanation, no ``` fences
2. Add metadata comment at top:
   (* Generated by CodeGenerationAgent/llm.v1
      Project: <projectId>  Iteration: <n>  Date: <date> *)
3. Variable names: PascalCase matching the PlanObject exactly
4. E-Stop inputs use normally-closed logic (FALSE = danger)
5. CASE statement must include ELSE branch that sets all outputs FALSE
6. RAG snippets are examples only, never copy undeclared variables from snippets
7. Use only variables declared in current PlanObject inputs, outputs, or internalVars
8. If any retrieved pattern conflicts with PlanObject variable semantics, PlanObject wins
9. Emergency_Stop semantics: TRUE = healthy, FALSE = active/open
10. Stop_PB semantics: TRUE = healthy, FALSE = pressed/open"""


class CodeGenerationAgent:
    def __init__(self, mode: CodeGenerationMode = "template_based") -> None:
        self.mode = mode
        self.rag_enabled = False

    async def generate_code(
        self,
        *,
        project_id: str,
        plan: PlanObject,
        patch_advice: list[str] | None = None,
        suggested_regeneration_prompt: str | None = None,
        iteration: int = 1,
        max_tokens_hint: int | None = None,
    ) -> CodeArtifact:
        if self.mode == "llm":
            return await self._generate_with_llm(
                project_id=project_id,
                plan=plan,
                patch_advice=patch_advice,
                suggested_regeneration_prompt=suggested_regeneration_prompt,
                iteration=iteration,
                max_tokens_hint=max_tokens_hint,
            )
        if self.mode != "template_based":
            raise ValueError(f"Unsupported CodeGenerationAgent mode: {self.mode}")
        return self._generate_template_based(
            project_id=project_id,
            plan=plan,
            patch_advice=patch_advice,
            suggested_regeneration_prompt=suggested_regeneration_prompt,
            iteration=iteration,
            max_tokens_hint=max_tokens_hint,
        )

    def _generate_template_based(
        self,
        *,
        project_id: str,
        plan: PlanObject,
        patch_advice: list[str] | None = None,
        suggested_regeneration_prompt: str | None = None,
        iteration: int = 1,
        max_tokens_hint: int | None = None,
    ) -> CodeArtifact:
        _ = max_tokens_hint
        repair_mode = bool(patch_advice or suggested_regeneration_prompt)
        source = self._source_for(plan)
        if repair_mode:
            source = self._annotate_repair(
                source=source,
                patch_advice=patch_advice or [],
                suggested_regeneration_prompt=suggested_regeneration_prompt,
            )
        created_at = self._utc_now()
        loc = len([line for line in source.splitlines() if line.strip()])
        generator = "template_based.repair.v1" if repair_mode else "template_based.v1"

        return CodeArtifact(
            projectId=project_id,
            artifactId=f"{project_id}-code-iter-{iteration}",
            language="structured-text",
            filename=f"{self._program_name(plan)}.st".lower(),
            source=source,
            iteration=iteration,
            generatedAt=created_at,
            metrics=CodeMetrics(
                loc=loc,
                cyclomaticComplexity=self._estimate_cyclomatic(source),
                maintainabilityIndex=max(65, min(95, 92 - self._estimate_cyclomatic(source) * 3)),
            ),
            metadata=CodeMetadata(
                generator=generator,
                iecStandard="IEC 61131-3",
                sourcePlanId=plan.projectId,
                createdAt=created_at,
                iteration=iteration,
            ),
        )

    async def _generate_with_llm(
        self,
        *,
        project_id: str,
        plan: PlanObject,
        patch_advice: list[str] | None,
        suggested_regeneration_prompt: str | None,
        iteration: int,
        max_tokens_hint: int | None = None,
    ) -> CodeArtifact:
        max_tokens = max_tokens_hint if isinstance(max_tokens_hint, int) and max_tokens_hint > 0 else 2000
        generation_started = time.perf_counter()
        plan_json = plan.model_dump_json(indent=2)
        rag_context = ""
        rag_sources: list[dict] = []
        if self.rag_enabled:
            try:
                from app.services.rag_service import get_rag_service

                rag = get_rag_service()
                domain = getattr(plan, "domain", "")
                inputs = [getattr(signal, "name", "") for signal in getattr(plan, "inputs", [])]
                outputs = [getattr(signal, "name", "") for signal in getattr(plan, "outputs", [])]
                safety = getattr(plan, "safetyConstraints", [])

                query = (
                    f"{domain} PLC controller "
                    f"inputs: {', '.join(inputs[:5])} "
                    f"outputs: {', '.join(outputs[:4])} "
                    f"safety: {' '.join(str(item) for item in safety[:2])}"
                )
                patterns = rag.retrieve(query=query, domain=domain, n_results=3)
                if patterns:
                    rag_sources = [
                        {
                            "id": pattern["id"],
                            "name": pattern["name"],
                            "similarity": pattern["similarity"],
                            "domain": pattern["domain"],
                            "patternType": pattern["patternType"],
                        }
                        for pattern in patterns
                    ]
                    rag_context = "\n\n=== RELEVANT IEC 61131-3 DESIGN PATTERNS ===\n"
                    rag_context += (
                        "Apply these validated patterns where appropriate. "
                        "Examples only: do not copy variables unless they exist in the current "
                        "PlanObject inputs, outputs, or internalVars. If pattern semantics conflict "
                        "with PlanObject semantics, PlanObject wins.\n"
                    )
                    for pattern in patterns:
                        rag_context += f"\n[{pattern['name']}] (match: {pattern['similarity']})\n"
                        if pattern["stSnippet"]:
                            rag_context += f"ST snippet:\n{pattern['stSnippet']}\n"
                        if pattern["safetyNotes"]:
                            rag_context += f"Safety rule: {pattern['safetyNotes']}\n"
                        if pattern["commonMistakes"]:
                            rag_context += f"Avoid: {'; '.join(pattern['commonMistakes'][:2])}\n"
                    rag_context += "\n=== END PATTERNS ===\n"
                    logger.info(f"[CodeGenAgent] RAG: {[pattern['name'] for pattern in patterns]}")
            except Exception as exc:
                logger.warning(f"[CodeGenAgent] RAG failed (non-critical): {exc}")

        repair_mode = bool(patch_advice) and iteration > 1
        previous_code = self._truncate_lines(self._source_for(plan), max_lines=60) if repair_mode else ""
        user_message = self._build_llm_user_message(
            plan_json=plan_json,
            rag_context=rag_context,
            iteration=iteration,
            patch_advice=patch_advice or [],
            suggested_regeneration_prompt=suggested_regeneration_prompt,
            previous_code=previous_code,
            repair_mode=repair_mode,
        )
        messages: list[dict[str, str]] = [{"role": "user", "content": user_message}]

        generated_source: str | None = None
        final_llm_response = None
        for attempt in range(2):
            llm_response = await llm_complete(
                system=CODEGEN_SYSTEM_PROMPT,
                messages=messages,
                temperature=0.2,
                max_tokens=max_tokens,
            )
            candidate = self._strip_markdown_fences(llm_response.content)
            if self._has_program_keyword(candidate):
                generated_source = candidate
                final_llm_response = llm_response
                break
            if attempt == 0:
                messages.extend(
                    [
                        {"role": "assistant", "content": llm_response.content},
                        {
                            "role": "user",
                            "content": "Your response is invalid because it does not contain a PROGRAM block. Return only raw IEC 61131-3 Structured Text code beginning with PROGRAM.",
                        },
                    ]
                )

        if generated_source is None:
            logger.warning("CodeGenerationAgent llm mode did not return a PROGRAM block after retry; falling back to template_based.")
            return self._generate_template_based(
                project_id=project_id,
                plan=plan,
                patch_advice=patch_advice,
                suggested_regeneration_prompt=suggested_regeneration_prompt,
                iteration=iteration,
                max_tokens_hint=max_tokens_hint,
            )
        if not self._all_outputs_present(generated_source, plan.outputs):
            logger.warning("CodeGenerationAgent llm mode omitted one or more PlanObject outputs; falling back to template_based.")
            return self._generate_template_based(
                project_id=project_id,
                plan=plan,
                patch_advice=patch_advice,
                suggested_regeneration_prompt=suggested_regeneration_prompt,
                iteration=iteration,
                max_tokens_hint=max_tokens_hint,
            )

        created_at = self._utc_now()
        loc = len([line for line in generated_source.splitlines() if line.strip()])
        complexity = self._estimate_cyclomatic(generated_source)
        generation_time_ms = int((time.perf_counter() - generation_started) * 1000)
        return CodeArtifact(
            projectId=project_id,
            artifactId=f"{project_id}-code-iter-{iteration}",
            language="structured-text",
            filename=f"{self._program_name(plan)}.st".lower(),
            source=generated_source,
            iteration=iteration,
            generatedAt=created_at,
            metrics=CodeMetrics(
                loc=loc,
                cyclomaticComplexity=complexity,
                maintainabilityIndex=max(65, min(95, 92 - complexity * 3)),
            ),
            metadata=CodeMetadata(
                generator="CodeGenerationAgent/llm.v1",
                iecStandard="IEC 61131-3",
                sourcePlanId=plan.projectId,
                createdAt=created_at,
                iteration=iteration,
                ragSources=rag_sources,
                llmProvider=final_llm_response.provider if final_llm_response else None,
                llmModel=final_llm_response.model if final_llm_response else None,
                generationMode="llm_rag" if rag_sources else "llm",
                tokensUsed=(
                    final_llm_response.input_tokens + final_llm_response.output_tokens
                    if final_llm_response
                    else None
                ),
                generationTimeMs=generation_time_ms,
            ),
        )

    # Signals each template reads or writes unconditionally. A template is used only when the plan
    # declares all of them, so generated code never references an undeclared signal (C-13).
    _TEMPLATE_SIGNALS: dict[str, frozenset[str]] = {
        "motor control": frozenset({"Motor_Run"}),
        "sequential batch": frozenset(
            {"Start_PB", "Emergency_Stop", "Abort_PB", "Reset_PB", "High_Level", "Low_Level", "Mix_Timer_Done"}
        ),
        "traffic control": frozenset(
            {"Vehicle_Detect", "Ped_Request", "Emergency_Flash", "Red_Light", "Amber_Light", "Green_Light", "Ped_Walk"}
        ),
        "process control": frozenset(
            {"Level_PV", "Low_SP", "High_SP", "HighHigh_SP", "Auto_Mode", "Inlet_Valve", "Outlet_Valve", "High_Alarm"}
        ),
        "safety interlocks": frozenset(
            {"Guard_Closed", "TwoHand_Left", "TwoHand_Right", "Reset_PB", "Fault_Input", "Machine_Enable", "Trip_Lamp", "Alarm_Horn"}
        ),
        "generic": frozenset({"Start_Cmd", "Stop_Cmd", "Reset_Cmd", "Process_Enable", "Fault_Indication"}),
    }

    def _source_for(self, plan: PlanObject) -> str:
        domain = canonical_domain(plan.domain)
        signals = {signal.name for signal in [*plan.inputs, *plan.outputs]}
        builders = {
            "motor control": self._motor_source,
            "sequential batch": self._batch_source,
            "traffic control": self._traffic_source,
            "process control": self._tank_source,
            "safety interlocks": self._safety_interlock_source,
        }

        builder = builders.get(domain)
        if builder is not None and self._TEMPLATE_SIGNALS[domain] <= signals:
            return builder(plan)
        if self._TEMPLATE_SIGNALS["generic"] <= signals:
            return self._generic_source(plan)
        return self._safe_outputs_source(plan)

    def _motor_source(self, plan: PlanObject) -> str:
        """Motor DOL (P1-22, D-031): normally closed stop, start on a rising edge, stop-dominant seal-in,
        and a latched fault that only Reset_PB clears. The reset runs after the run logic, so a Start
        press in the reset scan is consumed while the fault is still latched and cannot start the motor."""
        input_names = {signal.name for signal in plan.inputs}
        output_names = {signal.name for signal in plan.outputs}
        e_stop_name = "E_Stop" if "E_Stop" in input_names else ("Emergency_Stop" if "Emergency_Stop" in input_names else None)
        safety_terms = [term for term in [e_stop_name, "NOT Overload" if "Overload" in input_names else None] if term]
        has_reset = "Reset_PB" in input_names
        if has_reset:
            fault_set = ["IF NOT Safety_OK THEN", "    Fault_State := TRUE;", "END_IF;"]
            fault_reset = ["IF Fault_State AND Reset_PB AND Safety_OK THEN", "    Fault_State := FALSE;", "END_IF;"]
        else:
            # Without a reset input the fault follows the safety inputs; the seal-in still needs a new press.
            fault_set = ["Fault_State := NOT Safety_OK;"]
            fault_reset = []
        return self._assemble_program(
            plan,
            internal_variables=[
                ("Start_Edge", "R_TRIG"),
                ("Run_Cmd", "BOOL"),
                ("Fault_State", "BOOL"),
                ("Safety_OK", "BOOL"),
            ],
            logic=[
                "(* Motor DOL: NC stop, rising-edge start, stop-dominant seal-in, latched fault. *)",
                f"Safety_OK := {' AND '.join(safety_terms) if safety_terms else 'TRUE'};",
                *fault_set,
                "",
                f"Start_Edge(CLK := {'Start_PB' if 'Start_PB' in input_names else 'FALSE'});",
                f"IF {'NOT Stop_PB OR ' if 'Stop_PB' in input_names else ''}NOT Safety_OK OR Fault_State THEN",
                "    Run_Cmd := FALSE;",
                "ELSIF Start_Edge.Q THEN",
                "    Run_Cmd := TRUE;",
                "END_IF;",
                *fault_reset,
                "",
                "Motor_Run := Run_Cmd AND Safety_OK AND NOT Fault_State;",
                *(["Ready_Lamp := NOT Fault_State AND NOT Motor_Run;"] if "Ready_Lamp" in output_names else []),
                *(["Fault_Lamp := Fault_State;"] if "Fault_Lamp" in output_names else []),
            ],
        )

    def _traffic_source(self, plan: PlanObject) -> str:
        return self._assemble_program(
            plan,
            internal_variables=[
                ("Phase_Red", "BOOL"),
                ("Phase_Amber", "BOOL"),
            ],
            logic=[
                "(* Emergency flash forces a deterministic non-conflicting pattern. *)",
                "IF Emergency_Flash THEN",
                "    Red_Light := FALSE;",
                "    Amber_Light := TRUE;",
                "    Green_Light := FALSE;",
                "    Ped_Walk := FALSE;",
                "ELSE",
                "    (* Protected pedestrian service only during red vehicle phase. *)",
                "    Phase_Red := Ped_Request;",
                "    Phase_Amber := Vehicle_Detect AND NOT Phase_Red;",
                "",
                "    Red_Light := Phase_Red;",
                "    Amber_Light := Phase_Amber;",
                "    Green_Light := NOT Red_Light AND NOT Amber_Light;",
                "    Ped_Walk := Red_Light AND Ped_Request;",
                "END_IF;",
            ],
        )

    def _tank_source(self, plan: PlanObject) -> str:
        return self._assemble_program(
            plan,
            internal_variables=[
                ("Fill_Request", "BOOL"),
                ("High_Trip", "BOOL"),
            ],
            logic=[
                "(* Level limit handling. *)",
                "High_Trip := Level_PV >= HighHigh_SP;",
                "Fill_Request := Auto_Mode AND (Level_PV <= Low_SP) AND NOT High_Trip;",
                "",
                "(* Fill until high limit, then fail safe closed on high-high. *)",
                "IF Level_PV >= High_SP OR High_Trip THEN",
                "    Inlet_Valve := FALSE;",
                "ELSE",
                "    Inlet_Valve := Fill_Request;",
                "END_IF;",
                "",
                "Outlet_Valve := FALSE;",
                "High_Alarm := High_Trip;",
            ],
        )

    def _safety_interlock_source(self, plan: PlanObject) -> str:
        """Fail-safe interlock (P1-22, D-031): a latched trip that needs a manual reset, also after
        power-up, and two-hand control that needs both hands within 0.5 s and a full release before
        it re-arms. Machine_Enable is hold-to-run: releasing a hand drops it without tripping."""
        return self._assemble_program(
            plan,
            internal_variables=[
                ("Safety_OK", "BOOL"),
                ("Trip_State", "BOOL := TRUE"),
                ("Hands_Both", "BOOL"),
                ("Hands_Any", "BOOL"),
                ("Hands_Armed", "BOOL"),
                ("Hands_Active", "BOOL"),
                ("Sync_Timer", "TON"),
            ],
            logic=[
                "(* Latched trip; Trip_State starts TRUE, so power-up needs a manual reset. *)",
                "Safety_OK := Guard_Closed AND NOT Fault_Input;",
                "IF NOT Safety_OK THEN",
                "    Trip_State := TRUE;",
                "END_IF;",
                "IF Trip_State AND Reset_PB AND Safety_OK THEN",
                "    Trip_State := FALSE;",
                "END_IF;",
                "",
                "(* Two-hand control: both hands within 0.5 s; re-arm only after both are released. *)",
                "Hands_Both := TwoHand_Left AND TwoHand_Right;",
                "Hands_Any := TwoHand_Left OR TwoHand_Right;",
                "IF NOT Hands_Any THEN",
                "    Hands_Armed := TRUE;",
                "END_IF;",
                "Sync_Timer(IN := Hands_Any AND NOT Hands_Both AND NOT Hands_Active, PT := T#500ms);",
                "IF Sync_Timer.Q THEN",
                "    Hands_Armed := FALSE;",
                "END_IF;",
                "IF Hands_Both AND Hands_Armed THEN",
                "    Hands_Active := TRUE;",
                "END_IF;",
                "IF NOT Hands_Both THEN",
                "    (* One hand released after activation: stay disarmed until both are released. *)",
                "    IF Hands_Active AND Hands_Any THEN",
                "        Hands_Armed := FALSE;",
                "    END_IF;",
                "    Hands_Active := FALSE;",
                "END_IF;",
                "",
                "Machine_Enable := Safety_OK AND NOT Trip_State AND Hands_Active;",
                "Trip_Lamp := Trip_State;",
                "Alarm_Horn := Trip_State;",
            ],
        )

    def _batch_source(self, plan: PlanObject) -> str:
        """Sequential batch (P1-22, D-031): fill, mix, drain, then a Complete step that holds
        Batch_Complete until the next start. Start acts on a rising edge; an abort or emergency stop
        latches a fault that Reset_PB clears only when both are healthy."""
        output_names = {signal.name for signal in plan.outputs}
        step_outputs = [
            (name, step)
            for name, step in (("Fill_Valve", 1), ("Mixer_Motor", 2), ("Drain_Valve", 3), ("Batch_Complete", 4))
            if name in output_names
        ]
        return self._assemble_program(
            plan,
            internal_variables=[
                ("Start_Edge", "R_TRIG"),
                ("Step_State", "INT"),
                ("Fault_State", "BOOL"),
            ],
            logic=[
                "(* Sequential batch state machine with explicit fault handling. *)",
                "Start_Edge(CLK := Start_PB);",
                "IF NOT Emergency_Stop OR Abort_PB THEN",
                "    Step_State := 0;",
                "    Fault_State := TRUE;",
                "END_IF;",
                "",
                "(* Reset_PB clears the latched fault once shutdown signals are healthy. *)",
                "IF Fault_State AND Reset_PB AND Emergency_Stop AND NOT Abort_PB THEN",
                "    Fault_State := FALSE;",
                "END_IF;",
                "",
                "CASE Step_State OF",
                "    0: (* Idle *)",
                "        IF Start_Edge.Q AND NOT Fault_State THEN",
                "            Step_State := 1;",
                "        END_IF;",
                "    1: (* Fill *)",
                "        IF High_Level THEN",
                "            Step_State := 2;",
                "        END_IF;",
                "    2: (* Mix *)",
                "        IF Mix_Timer_Done THEN",
                "            Step_State := 3;",
                "        END_IF;",
                "    3: (* Drain *)",
                "        IF Low_Level THEN",
                "            Step_State := 4;",
                "        END_IF;",
                "    4: (* Complete: held until the next start *)",
                "        IF Start_Edge.Q AND NOT Fault_State THEN",
                "            Step_State := 1;",
                "        END_IF;",
                "    ELSE",
                "        Step_State := 0;",
                "END_CASE;",
                "",
                "(* Outputs are driven from PlanObject outputs only. *)",
                *[f"{name} := (Step_State = {step}) AND NOT Fault_State;" for name, step in step_outputs],
                *(
                    [
                        "",
                        "(* Safety force-off after output assignments (scan order guarantee). *)",
                        "IF Fault_State THEN",
                        *[f"    {name} := FALSE;" for name, _ in step_outputs],
                        "END_IF;",
                    ]
                    if step_outputs
                    else []
                ),
            ],
        )

    def _safe_outputs_source(self, plan: PlanObject) -> str:
        """Used when no template matches the plan's domain and signals: every BOOL output is held FALSE
        instead of generating code that reads signals the plan does not declare (C-13)."""
        return self._assemble_program(
            plan,
            internal_variables=[],
            logic=[
                "(* No template matches this PlanObject; every BOOL output is held FALSE. *)",
                *[f"{signal.name} := FALSE;" for signal in plan.outputs if signal.type.upper() == "BOOL"],
            ],
        )

    def _generic_source(self, plan: PlanObject) -> str:
        return self._assemble_program(
            plan,
            internal_variables=[
                ("Run_State", "BOOL"),
                ("Fault_State", "BOOL"),
            ],
            logic=[
                "(* Generic safe enable fallback. *)",
                "IF Stop_Cmd THEN",
                "    Run_State := FALSE;",
                "END_IF;",
                "",
                "IF Reset_Cmd THEN",
                "    Fault_State := FALSE;",
                "END_IF;",
                "",
                "IF Start_Cmd AND NOT Fault_State THEN",
                "    Run_State := TRUE;",
                "END_IF;",
                "",
                "Process_Enable := Run_State AND NOT Fault_State;",
                "Fault_Indication := Fault_State;",
            ],
        )

    def _assemble_program(
        self,
        plan: PlanObject,
        *,
        internal_variables: list[tuple[str, str]],
        logic: list[str],
    ) -> str:
        sections = [
            f"PROGRAM {self._program_name(plan)}",
            "(* Generated by CodeGenerationAgent template_based.v1 from PlanObject. *)",
            "",
            "(* Inputs derived from the PlanObject. *)",
            "VAR_INPUT",
            *self._declarations(plan.inputs),
            "END_VAR",
            "",
            "(* Outputs derived from the PlanObject. *)",
            "VAR_OUTPUT",
            *self._declarations(plan.outputs),
            "END_VAR",
        ]

        if internal_variables:
            sections.extend([
                "",
                "(* Internal state and helper variables. *)",
                "VAR",
                *[f"    {name} : {signal_type};" for name, signal_type in internal_variables],
                "END_VAR",
            ])

        sections.extend([
            "",
            "(* Main control logic. *)",
            *logic,
            "",
            "END_PROGRAM",
        ])

        return "\n".join(sections)

    @staticmethod
    def _declarations(signals: list[PlanSignal]) -> list[str]:
        declarations: list[str] = []
        for signal in signals:
            if signal.name == "Stop_PB":
                declarations.append("    Stop_PB : BOOL;  (* Normally closed stop pushbutton: TRUE = healthy, FALSE = pressed *)")
                continue
            declarations.append(f"    {signal.name} : {signal.type};  (* {signal.description} *)")
        return declarations

    def _annotate_repair(
        self,
        *,
        source: str,
        patch_advice: list[str],
        suggested_regeneration_prompt: str | None,
    ) -> str:
        repair_lines = [
            "(* Repair loop: regenerated from DebuggingReport patch advice. *)",
            *[f"(* Repair advice {index}: {self._comment_safe(advice)} *)" for index, advice in enumerate(patch_advice, start=1)],
        ]
        if suggested_regeneration_prompt:
            repair_lines.append(f"(* Repair prompt: {self._comment_safe(suggested_regeneration_prompt)} *)")

        repaired = source.replace("template_based.v1", "template_based.repair.v1", 1)
        marker = "(* Inputs derived from the PlanObject. *)"
        if marker in repaired:
            return repaired.replace(marker, "\n".join([*repair_lines, "", marker]), 1)
        return "\n".join([*repair_lines, repaired])

    def _build_llm_user_message(
        self,
        *,
        plan_json: str,
        rag_context: str,
        iteration: int,
        patch_advice: list[str],
        suggested_regeneration_prompt: str | None,
        previous_code: str,
        repair_mode: bool,
    ) -> str:
        if not repair_mode:
            return (
                "PLAN OBJECT:\n"
                f"{plan_json}\n"
                f"{rag_context}\n"
                "Generate the PROGRAM block now."
            )

        violated_constraint = patch_advice[0] if patch_advice else "Not specified."
        root_cause = (
            patch_advice[1]
            if len(patch_advice) > 1
            else (suggested_regeneration_prompt or "Not specified.")
        )
        patch_directive = (
            " | ".join(item.strip() for item in patch_advice if item.strip())
            if patch_advice
            else (suggested_regeneration_prompt or "Regenerate a corrected PROGRAM block.")
        )
        error_text = f"{violated_constraint} {root_cause} {patch_directive}".lower()
        syntax_violation_note = ""
        if iteration > 1 and ("invalid expression" in error_text or "missing" in error_text):
            syntax_violation_note = (
                "\nSYNTAX RULE VIOLATION DETECTED:\n"
                "All assignment statements must be on ONE LINE.\n"
                "Example of the fix needed:\n"
                "  WRONG:  X := A OR\n"
                "               B;\n"
                "  RIGHT:  X := A OR B;\n"
                "Do not split any assignment across multiple lines.\n"
            )
        do_not_change = "PlanObject signal names, IEC data types, and overall PROGRAM structure."
        return (
            "PLAN OBJECT:\n"
            f"{plan_json}\n"
            f"{rag_context}\n"
            f"PREVIOUS CODE FAILED (iteration {iteration}):\n"
            f"Violated constraint: {violated_constraint}\n"
            f"Root cause: {root_cause}\n"
            f"Patch directive: {patch_directive}\n"
            f"DO NOT change: {do_not_change}\n\n"
            f"{syntax_violation_note}"
            "PREVIOUS CODE:\n"
            f"{previous_code}\n\n"
            "Fix the violation. Generate corrected PROGRAM block."
        )

    @staticmethod
    def _truncate_lines(value: str, *, max_lines: int) -> str:
        lines = value.splitlines()
        if len(lines) <= max_lines:
            return value
        return "\n".join(lines[:max_lines])

    @staticmethod
    def _strip_markdown_fences(content: str) -> str:
        stripped = content.strip()
        if stripped.startswith("```"):
            lines = stripped.splitlines()
            if lines:
                lines = lines[1:]
            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]
            stripped = "\n".join(lines).strip()
        return stripped

    @staticmethod
    def _has_program_keyword(source: str) -> bool:
        return bool(re.search(r"\bPROGRAM\b", source, flags=re.IGNORECASE))

    @staticmethod
    def _all_outputs_present(source: str, outputs: list[PlanSignal]) -> bool:
        missing = [signal.name for signal in outputs if not re.search(rf"\b{re.escape(signal.name)}\b", source)]
        return not missing

    @staticmethod
    def _comment_safe(value: str) -> str:
        return value.replace("*)", "* )").strip()

    @staticmethod
    def _program_name(plan: PlanObject) -> str:
        sanitized = "".join(char if char.isalnum() else "_" for char in plan.projectId)
        return f"PLC_{sanitized}_Controller"

    @staticmethod
    def _normalized_domain(plan: PlanObject) -> str:
        return " ".join(plan.domain.strip().lower().split())

    @staticmethod
    def _estimate_cyclomatic(source: str) -> int:
        branch_tokens = ["IF ", "ELSIF ", "CASE ", "FOR ", "WHILE "]
        return 1 + sum(source.count(token) for token in branch_tokens)

    @staticmethod
    def _utc_now() -> str:
        return datetime.now(timezone.utc).replace(microsecond=0).isoformat()
